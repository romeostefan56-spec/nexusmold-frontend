function i18nDetectLang() {
    const saved = localStorage.getItem('nexus_lang');
    if (saved && I18N[saved]) return saved;
    const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : 'es';
}
function i18nCurrentLang() {
    const lang = localStorage.getItem('nexus_lang');
    return (lang && I18N[lang]) ? lang : i18nDetectLang();
}
function t(key, params) {
    const lang = i18nCurrentLang();
    let text = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
    if (params) {
        Object.keys(params).forEach(p => { text = text.split('{' + p + '}').join(params[p]); });
    }
    return text;
}
function currentLocale() {
    return I18N_LOCALES[i18nCurrentLang()] || 'es-ES';
}
function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    document.documentElement.lang = i18nCurrentLang();
    document.querySelectorAll('select[data-i18n-selector]').forEach(sel => { sel.value = i18nCurrentLang(); });
}
function setLang(lang) {
    if (!I18N[lang]) return;
    localStorage.setItem('nexus_lang', lang);
    applyI18n();
}
document.addEventListener('DOMContentLoaded', () => {
    if (!localStorage.getItem('nexus_lang')) localStorage.setItem('nexus_lang', i18nDetectLang());
    applyI18n();
});
